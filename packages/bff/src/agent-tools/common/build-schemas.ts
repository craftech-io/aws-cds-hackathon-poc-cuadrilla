// `npm run tools:build-schemas`: writes infra/agent-tool-schemas.ts, the `inlinePayload` of the five
// `GatewayTarget`s (infra/agent-tools.ts) and the schemas the Cedar policies are validated against
// (infra/policy.ts), from the zod schemas of `agent-tools/<target>/schema.ts`. It fails, writing
// nothing, when a tool has no schema, a target has no tool, a name repeats or a schema needs a keyword
// the Gateway does not support (docs/architecture.md §18).
//
//   npm run tools:build-schemas              write the module if it changed
//   npm run tools:build-schemas -- --check   exit 1 if the committed module is stale
import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import { TOOL_CATALOG } from "./catalog";
import { TOOL_TARGETS, type ToolDefinition, type ToolTarget } from "./definition";
import { type GatewayToolSchema, GatewaySchemaError, gatewayToolSchema } from "./gateway-schema";

/** Gateway tools of the POC (docs/design-brief.md §5.3). */
export const EXPECTED_TOOL_COUNT = 12;

/** Where the generated module lives, from the repository root. */
export const SCHEMA_MODULE_PATH = "infra/agent-tool-schemas.ts";

export type GatewayPayloads = Readonly<Record<ToolTarget, { readonly inlinePayload: readonly GatewayToolSchema[] }>>;

/** The payload of every target; throws `GatewaySchemaError` listing every problem found. */
export function buildGatewayPayloads(catalog: Readonly<Record<ToolTarget, readonly ToolDefinition[]>> = TOOL_CATALOG): GatewayPayloads {
  const problems: string[] = [];
  const seen = new Set<string>();
  const payloads = {} as Record<ToolTarget, { inlinePayload: GatewayToolSchema[] }>;
  for (const target of TOOL_TARGETS) {
    const tools = catalog[target] ?? [];
    if (tools.length === 0) problems.push(`target ${target} has no tool`);
    const inlinePayload: GatewayToolSchema[] = [];
    for (const tool of tools) {
      if (tool?.args === undefined) {
        problems.push(`a tool of target ${target} has no schema`);
        continue;
      }
      if (tool.target !== target) problems.push(`${tool.name} is declared for ${tool.target} but listed under ${target}`);
      if (seen.has(tool.name)) problems.push(`tool name ${tool.name} repeats`);
      seen.add(tool.name);
      try {
        inlinePayload.push(gatewayToolSchema(tool));
      } catch (error) {
        problems.push(error instanceof Error ? error.message : String(error));
      }
    }
    payloads[target] = { inlinePayload };
  }
  if (problems.length > 0) throw new GatewaySchemaError(`Gateway tool schemas:\n  ${problems.join("\n  ")}`);
  return payloads;
}

export function toolCount(payloads: GatewayPayloads): number {
  return TOOL_TARGETS.reduce((total, target) => total + payloads[target].inlinePayload.length, 0);
}

/** The TypeScript module infra/ imports: one line per tool, stable order, no timestamp. */
export function renderSchemaModule(payloads: GatewayPayloads): string {
  const lines = [
    "// Generated by `npm run tools:build-schemas` (packages/bff/src/agent-tools/common/build-schemas.ts) from the",
    "// zod schemas of packages/bff/src/agent-tools/<target>/schema.ts. Do not edit: change the zod schema and run",
    "// the script again (agent-tools/common/build-schemas.test.ts fails while this file is stale).",
    "// `gatewayToolSchemas.<target>.inlinePayload` is the `toolSchema.inlinePayload` of that GatewayTarget",
    "// (infra/agent-tools.ts) and the schema set infra/policy.ts validates the Cedar policies against.",
    'import type { GatewayTarget } from "./policy-rules";',
    "",
    'export type GatewaySchemaType = "string" | "number" | "integer" | "boolean" | "array" | "object";',
    "export interface GatewaySchemaDefinition { type: GatewaySchemaType; description?: string; properties?: Record<string, GatewaySchemaDefinition>; required?: string[]; items?: GatewaySchemaDefinition }",
    "export interface GatewayToolDefinition { name: string; description: string; inputSchema: GatewaySchemaDefinition }",
    "",
    "export const gatewayToolSchemas: Record<GatewayTarget, { inlinePayload: GatewayToolDefinition[] }> = {",
  ];
  for (const target of TOOL_TARGETS) {
    lines.push(`  ${target}: {`, "    inlinePayload: [");
    for (const tool of payloads[target].inlinePayload) lines.push(`      ${JSON.stringify(tool)},`);
    lines.push("    ],", "  },");
  }
  lines.push("};", "");
  return lines.join("\n");
}

function repositoryRoot(): string {
  return fileURLToPath(new URL("../../../../../", import.meta.url));
}

export interface BuildResult {
  readonly path: string;
  readonly changed: boolean;
  readonly targets: number;
  readonly tools: number;
}

/** Builds and writes (or, with `check`, only compares) the generated module. */
export function buildSchemas(options: { readonly check?: boolean; readonly root?: string } = {}): BuildResult {
  const payloads = buildGatewayPayloads();
  const tools = toolCount(payloads);
  if (tools !== EXPECTED_TOOL_COUNT) throw new GatewaySchemaError(`expected ${EXPECTED_TOOL_COUNT} Gateway tools, found ${tools}`);
  const path = resolve(options.root ?? repositoryRoot(), SCHEMA_MODULE_PATH);
  const next = renderSchemaModule(payloads);
  let current: string | undefined;
  try {
    current = readFileSync(path, "utf8");
  } catch {
    current = undefined;
  }
  const changed = current !== next;
  if (changed && options.check !== true) writeFileSync(path, next);
  return { path: SCHEMA_MODULE_PATH, changed, targets: TOOL_TARGETS.length, tools };
}

function main(argv: readonly string[]): number {
  const check = argv.includes("--check");
  try {
    const result = buildSchemas({ check });
    if (check && result.changed) {
      process.stderr.write(`${result.path} is stale: run npm run tools:build-schemas\n`);
      return 1;
    }
    process.stdout.write(`${result.path}: ${result.targets} payloads, ${result.tools} tools${result.changed && !check ? " (written)" : " (up to date)"}\n`);
    return 0;
  } catch (error) {
    process.stderr.write(`${error instanceof Error ? error.message : String(error)}\n`);
    return 1;
  }
}

const entry = process.argv[1];
if (entry !== undefined && import.meta.url === pathToFileURL(resolve(entry)).href) process.exitCode = main(process.argv.slice(2));
