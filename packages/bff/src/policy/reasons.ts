  "BRIDGE_ACTIVE",
  // CP-ROSTER
  "NO_ROSTER",
  "NOT_ON_ROSTER",
  // CP-QUIET-HOURS (a deferral, never a drop)
  "QUIET_HOURS",
  // CP-ONE-DAYSTART
  "DAY_START_ALREADY_SENT",
  // CP-WA-24H
  "WINDOW_CLOSED",
