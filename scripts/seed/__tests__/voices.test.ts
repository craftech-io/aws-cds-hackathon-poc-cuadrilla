// The committed voice notes against their datasheet (docs/seed-spec.md §11, §14 invariant 9):
// Polly parameters, valid Ogg/Opus with good CRCs, mono, measured durations, sha256, the texts from
// audio/texts.ts, the transcripts of the LF fake and the noise note reproducible from its seed.
import { existsSync, readFileSync } from "node:fs";
import { join } from "node:path";
import { fileURLToPath } from "node:url";
import { describe, expect, it } from "vitest";
import { DEFAULT_OPERATOR_NAME } from "../../../packages/bff/src/copy/brand";
import { matchSafetyLexicon } from "../../../packages/bff/src/copy/safety-lexicon";
import { findTerms, listFromEnv } from "../../lint/forbidden-terms";
import { noisePcm } from "../audio/noise";
import { isOgg, oggOpusInfo } from "../audio/ogg";
import { AUDIO_DATASHEET_FILE, AudioDatasheet, POLLY_PARAMS } from "../audio/schema";
import { LONG_NOTE_PARAGRAPH, VOICE_NOTES, allVoiceTexts } from "../audio/texts";
import { sha256Hex } from "../photos/prng";
import { fakeTranscript, pollyInput, voiceFile } from "../voices";

const ROOT = fileURLToPath(new URL("../../..", import.meta.url));
const read = (path: string) => readFileSync(join(ROOT, path));
const datasheet = AudioDatasheet.parse(JSON.parse(read(AUDIO_DATASHEET_FILE).toString("utf8")));
const byId = new Map(datasheet.notes.map((note) => [note.voiceId, note]));

// docs/seed-spec.md §11, restated: who speaks each note (`null` = generated by code).
const VOICE_OF: Readonly<Record<string, "Mia" | "Andres" | null>> = {
  "vn-01": "Andres",
  "vn-02": "Andres",
  "vn-03": "Mia",
  "vn-04": "Andres",
  "vn-05": "Mia",
  "vn-06": "Mia",
  "vn-07": "Andres",
  "vn-08": "Mia",
  "vn-09": null,
  "vn-10": "Andres",
  "vn-11": "Mia",
  "vn-12": "Andres",
};

describe("voice notes datasheet (docs/seed-spec.md §11)", () => {
  it("lists the 12 notes in order, with the texts of audio/texts.ts", () => {
    expect(datasheet.notes.map((note) => note.voiceId)).toEqual(Object.keys(VOICE_OF));
    for (const note of VOICE_NOTES) {
      expect(byId.get(note.voiceId), note.voiceId).toMatchObject({ text: note.text, repeat: note.repeat, use: note.use, flows: [...note.flows], file: voiceFile(note.voiceId) });
    }
  });

  it.each(Object.entries(VOICE_OF))("%s is spoken by %s with Polly neural es-MX, Ogg/Opus 48 kHz", (voiceId, voice) => {
    const entry = byId.get(voiceId);
    if (voice === null) {
      expect(entry).toMatchObject({ source: "code", polly: null, speaker: null, code: { generator: "scripts/seed/audio/noise.ts", seed: 20260926 } });
      return;
    }
    expect(entry).toMatchObject({ source: "polly", code: null, speaker: voice === "Andres" ? "Andrés" : "Mia" });
    expect(entry?.polly).toEqual({ ...POLLY_PARAMS, voiceId: voice, textType: voiceId === "vn-10" ? "ssml" : "text" });
  });

  it("[FL-017] [FL-018] [FL-070] the transcripts of the LF fake are the spoken words, and nothing for the noise", () => {
    for (const note of VOICE_NOTES) expect(byId.get(note.voiceId)?.transcript, note.voiceId).toEqual(fakeTranscript(note));
    expect(byId.get("vn-09")?.transcript).toEqual({ text: "", confidence: 0 });
    const main = byId.get("vn-01")?.transcript.text.toLowerCase() ?? "";
    expect(main).toContain("onu");
    expect(main).toContain("pon");
  });

  it("[FL-069] [FL-070] vn-05 trips the safety lexicon and vn-12 does not (the agent has to detect it)", () => {
    expect(matchSafetyLexicon(byId.get("vn-05")?.text ?? "")?.category).toBe("ELECTRICAL");
    expect(matchSafetyLexicon(byId.get("vn-12")?.text ?? "")).toBeNull();
  });
});

describe("voice note files (invariant 9)", () => {
  it.each(datasheet.notes.map((note) => [note.voiceId, note] as const))("%s: valid mono Ogg/Opus with the datasheet's duration and sha256", (voiceId, entry) => {
    expect(existsSync(join(ROOT, entry.file))).toBe(true);
    const bytes = read(entry.file);
    expect(isOgg(bytes)).toBe(true);
    const info = oggOpusInfo(bytes);
    expect(info.channels).toBe(1);
    expect(info.durationSec).toBeCloseTo(entry.durationSec, 2);
    expect(bytes.length).toBe(entry.bytes);
    expect(sha256Hex(bytes)).toBe(entry.sha256);
    if (voiceId === "vn-10") expect(entry.durationSec).toBeGreaterThanOrEqual(150);
    else expect(entry.durationSec).toBeLessThanOrEqual(15);
  });

  it("rejects a file with a broken page", () => {
    const bytes = Buffer.from(read(voiceFile("vn-01")));
    bytes[60] = (bytes[60] ?? 0) ^ 0xff;
    expect(() => oggOpusInfo(bytes)).toThrow(/CRC|capture|truncated|OpusHead/);
    expect(() => oggOpusInfo(Buffer.from("not an ogg"))).toThrow(/OggS/);
  });
});

describe("how the notes are made", () => {
  it("[FL-018] vn-09 comes from the seed: the same PCM every time", () => {
    const pcm = noisePcm();
    expect(sha256Hex(pcm)).toBe(byId.get("vn-09")?.code?.pcmSha256);
    expect(sha256Hex(noisePcm())).toBe(sha256Hex(pcm));
    expect(byId.get("vn-09")?.durationSec).toBeCloseTo(8, 1);
  });

  it("[FL-018] vn-10 reads the scope paragraph six times as SSML, within Polly's 3000 billed characters", () => {
    const long = VOICE_NOTES.find((note) => note.voiceId === "vn-10");
    expect(long?.text).toBe(LONG_NOTE_PARAGRAPH);
    const input = long === undefined ? undefined : pollyInput(long);
    expect(input?.textType).toBe("ssml");
    expect(input?.text.startsWith("<speak>")).toBe(true);
    expect(LONG_NOTE_PARAGRAPH.length * (long?.repeat ?? 0)).toBeLessThanOrEqual(3000);
    expect(pollyInput({ ...(long ?? VOICE_NOTES[0]!), text: "a < b & c", repeat: 2 }).text).toContain("a &lt; b &amp; c");
  });

  it("never names the operator and has no term of the external list", () => {
    for (const text of allVoiceTexts()) expect(text.includes(DEFAULT_OPERATOR_NAME), text).toBe(false);
    const list = listFromEnv(process.env);
    if (list.ok) expect(findTerms("voice texts", allVoiceTexts().join("\n"), list.terms)).toEqual([]);
  });
});
