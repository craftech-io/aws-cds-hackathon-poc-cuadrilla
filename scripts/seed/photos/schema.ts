// Shapes of what `npm run seed:photos` writes (docs/seed-spec.md §10, §10.1): the photo specs of the
// catalogs, the two datasheets (`datasheet.json` for the 60 photos of the set, `datasheet-aux.json`
// for the historical and seeding renders and the template sample) and the scripted validator output
// (`scripted-verdicts.json`). The seed generator (EVAL#PHOTOS), the loader, the U/LF fakes and the
// evaluation read these files through these schemas.
import { OnuOperState, OnuSerial, OpticalClass, PhotoId, PhotoItem, RejectReason, RuleId, Verdict, WorkOrderId } from "@cuadrilla/shared";
import { z } from "zod";

export const GENERATOR = "scripts/seed/photos/render.ts";
export const GENERATOR_VERSION = "1.0.0";
/** Legend every photo carries (docs/seed-spec.md §10). */
export const ORIGIN = "generated by scripts/seed/photos/render.ts, seed 20260926";
export const PHOTO_FORMAT = { mime: "image/jpeg", width: 1280, height: 960, maxBytes: 400 * 1024 } as const;

export const Template = z.enum(["meter", "label", "rosette", "onu-device", "router", "cable-reel", "fake-certificate"]);
export type Template = z.infer<typeof Template>;

export const BackgroundKind = z.enum(["wall", "wood", "sidewalk", "none"]);
export type BackgroundKind = z.infer<typeof BackgroundKind>;

/** Values a template draws. */
export const Drawn = z.discriminatedUnion("template", [
  z
    .object({
      template: z.literal("meter"),
      readingDbm: z.number(),
      wavelengthNm: z.union([z.literal(1310), z.literal(1490), z.literal(1550)]),
      sticker: z.array(z.string()).optional(),
    })
    .strict(),
  z
    .object({
      template: z.literal("label"),
      serial: OnuSerial,
      mac: z.string().regex(/^02(?::[0-9A-F]{2}){5}$/),
      ssid: z.string().regex(/^RED-[A-Z0-9]{4}$/),
      wifiKey: z.string().regex(/^[A-Z0-9]{8}$/),
      injection: z.array(z.string()).optional(),
    })
    .strict(),
  z.object({ template: z.literal("rosette"), lidOpen: z.boolean() }).strict(),
  z.object({ template: z.literal("onu-device") }).strict(),
  z.object({ template: z.literal("router") }).strict(),
  z.object({ template: z.literal("cable-reel") }).strict(),
  z.object({ template: z.literal("fake-certificate") }).strict(),
]);
export type Drawn = z.infer<typeof Drawn>;

const Edge = z.enum(["left", "right", "top", "bottom"]);

/** Programmatic degradations, with their parameters (docs/seed-spec.md §10). */
export const Degradation = z.discriminatedUnion("kind", [
  z.object({ kind: z.literal("gaussian-blur"), radiusPx: z.number().min(1).max(30) }).strict(),
  z.object({ kind: z.literal("motion-blur"), lengthPx: z.number().min(1).max(60), angleDeg: z.literal(0) }).strict(),
  z.object({ kind: z.literal("glare"), target: z.string(), opacity: z.number().min(0).max(1), spread: z.number().positive() }).strict(),
  z.object({ kind: z.literal("crop"), target: z.string(), edge: Edge, visibleFraction: z.number().min(0).max(1) }).strict(),
  z.object({ kind: z.literal("underexposure"), brightness: z.number().min(0).max(1) }).strict(),
  z.object({ kind: z.literal("perspective"), angleDeg: z.number().min(-25).max(25) }).strict(),
  z.object({ kind: z.literal("rotation"), angleDeg: z.number() }).strict(),
  z.object({ kind: z.literal("zoom-out"), fill: z.number().min(0.05).max(1) }).strict(),
  z.object({ kind: z.literal("close-up"), target: z.string() }).strict(),
  z.object({ kind: z.literal("occlusion"), target: z.string(), by: z.literal("finger") }).strict(),
  z.object({ kind: z.literal("jpeg-quality"), quality: z.int().min(10).max(100) }).strict(),
]);
export type Degradation = z.infer<typeof Degradation>;

export const PhotoGroup = z.enum(["set", "hist", "seed"]);
export type PhotoGroup = z.infer<typeof PhotoGroup>;

/** A photo to render and its label: what the validator should conclude for the order it is sent to. */
export const PhotoSpec = z
  .object({
    photoId: PhotoId,
    group: PhotoGroup,
    /** Checklist item the photo is sent for. */
    item: PhotoItem,
    drawn: Drawn,
    degradations: z.array(Degradation),
    background: BackgroundKind.optional(),
    expectedVerdict: Verdict,
    expectedReason: RejectReason.nullable(),
    /** Other reasons that also count as right (ph-label-17: blurry and with glare). */
    acceptedReasons: z.array(RejectReason),
    /** `UNSURE` also counts as right (every `UNREADABLE` photo). */
    acceptsUnsure: z.boolean(),
    /** Order the photo is evaluated against: its class, its ONU serial and the orchestrator's reading. */
    opticalClass: OpticalClass,
    orderSerial: OnuSerial,
    orchestratorRxDbm: z.number(),
    operState: OnuOperState,
    /** Order of the demo seed whose story uses this photo, if any. */
    workOrderId: WorkOrderId.nullable(),
    /** The file is a byte copy of another photo (ph-adv-04). */
    sameBytesAs: PhotoId.optional(),
    /** State the photo needs to reach its label (ph-adv-04: an earlier PASS evidence with its bytes). */
    precondition: z.object({ seededPassEvidenceOf: PhotoId }).strict().optional(),
    description: z.string().min(1),
  })
  .strict();
export type PhotoSpec = z.infer<typeof PhotoSpec>;

/** Random framing of one render, drawn from the photo's own stream and recorded in the datasheet. */
export const Framing = z
  .object({
    background: BackgroundKind,
    backgroundSeed: z.int().min(0),
    tiltDeg: z.number(),
    offsetX: z.number(),
    offsetY: z.number(),
    fill: z.number().positive(),
    cast: z.enum(["neutral", "warm", "cool"]),
    jpegQuality: z.int().min(10).max(100),
  })
  .strict();
export type Framing = z.infer<typeof Framing>;

export const PhotoEntry = PhotoSpec.extend({
  file: z.string().regex(/^scripts\/seed\/photos\/out\/ph-[A-Za-z0-9_-]+\.jpg$/),
  sha256: z.string().regex(/^[0-9a-f]{64}$/),
  bytes: z.int().positive(),
  width: z.literal(PHOTO_FORMAT.width),
  height: z.literal(PHOTO_FORMAT.height),
  /** `null` for a byte copy (`sameBytesAs`). */
  framing: Framing.nullable(),
  origin: z.literal(ORIGIN),
}).strict();
export type PhotoEntry = z.infer<typeof PhotoEntry>;

const Renderer = z.object({ engine: z.literal("chromium"), playwright: z.string(), browserVersion: z.string() }).strict();

const DatasheetHeader = {
  generator: z.literal(GENERATOR),
  generatorVersion: z.literal(GENERATOR_VERSION),
  seed: z.literal(20260926),
  origin: z.literal(ORIGIN),
  renderer: Renderer,
  format: z.object({ mime: z.literal("image/jpeg"), width: z.literal(1280), height: z.literal(960), maxBytes: z.literal(PHOTO_FORMAT.maxBytes) }).strict(),
};

export const Datasheet = z.object({ ...DatasheetHeader, photos: z.array(PhotoEntry) }).strict();
export type Datasheet = z.infer<typeof Datasheet>;

/** A document rendered with the photos: the synthetic sample of the certificate template header. */
export const DocumentEntry = z
  .object({
    documentId: z.literal("acta-muestra"),
    file: z.literal("scripts/seed/photos/templates/acta-muestra.pdf"),
    /** Key in the `Seed` bucket (copy/templates.ts CERTIFICATE_TEMPLATE_SAMPLE_KEY). */
    seedKey: z.string(),
    mime: z.literal("application/pdf"),
    sha256: z.string().regex(/^[0-9a-f]{64}$/),
    bytes: z.int().positive(),
    generator: z.literal("scripts/seed/photos/acta-sample.ts"),
    description: z.string(),
  })
  .strict();
export type DocumentEntry = z.infer<typeof DocumentEntry>;

export const AuxDatasheet = z.object({ ...DatasheetHeader, photos: z.array(PhotoEntry), documents: z.array(DocumentEntry) }).strict();
export type AuxDatasheet = z.infer<typeof AuxDatasheet>;

// ---- Scripted validator output (U and LF fakes) ---------------------------------------------------

export const PhotoSubject = z.enum(["POWER_METER", "ONU_LABEL", "ROSETTE", "OTHER"]);
export type PhotoSubject = z.infer<typeof PhotoSubject>;

/** Input of `record_verdict` as the scripted fake returns it (docs/design-brief.md §5.10). */
export const RecordVerdictInput = z
  .object({
    subject: PhotoSubject,
    quality: z
      .object({
        focus: z.enum(["SHARP", "BLURRY"]),
        glare: z.enum(["NONE", "PARTIAL", "OBSCURING"]),
        framing: z.enum(["COMPLETE", "CROPPED", "TOO_FAR"]),
        lighting: z.enum(["GOOD", "LOW", "DARK"]),
      })
      .strict(),
    readingDbm: z.number().nullable(),
    wavelengthNm: z.int().nullable(),
    serial: z.string().nullable(),
    modelVerdict: z.enum(["PASS", "REJECT"]),
    reasonCode: RejectReason.nullable(),
    confidence: z.number().min(0).max(1),
  })
  .strict();
export type RecordVerdictInput = z.infer<typeof RecordVerdictInput>;

export const ScriptedVerdict = z
  .object({
    photoId: PhotoId,
    item: PhotoItem,
    source: z.literal("SCRIPTED"),
    /** `false` only for a duplicate: the pre-check rejects it before any model call. */
    modelCalled: z.boolean(),
    recordVerdict: RecordVerdictInput,
    /** Verdict after the deterministic checks, for the order of the datasheet entry. */
    finalVerdict: Verdict,
    finalReason: RejectReason.nullable(),
    /** `VAL-*` checks that decide the final verdict (empty when the model's verdict stands). */
    checks: z.array(RuleId),
  })
  .strict();
export type ScriptedVerdict = z.infer<typeof ScriptedVerdict>;

export const ScriptedVerdicts = z
  .object({
    label: z.literal("scripted"),
    note: z.string(),
    generator: z.literal(GENERATOR),
    seed: z.literal(20260926),
    rubricVersion: z.literal("v001"),
    verdicts: z.array(ScriptedVerdict),
  })
  .strict();
export type ScriptedVerdicts = z.infer<typeof ScriptedVerdicts>;
